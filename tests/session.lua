local Session = require("game.session")
local game = Session.new("thrifty", 1)
local view = game:view()
assert(view.phase == "rolling" and view.turn == 1 and view.rolls_used == 1)
assert(table.concat(view.dice, ",") == "2,2,6,3,5")
assert(game:toggle_hold(1))
assert(game:roll())
assert(game:view().dice[1] == 2 and game:view().rolls_used == 2)
assert(game:roll())
assert(not game:roll())
assert(game:begin_placement())
assert(not game:roll())
print("session rolling passed")
local placed = Session.new("pair_pay", 1)
assert(placed:toggle_hold(1))
assert(placed:begin_placement())
assert(placed:adjust(1, -1))
assert(placed:view().dice[1] == 1 and placed:view().adjustments == 1)
assert(not placed:adjust(1, -1))
assert(placed:place(1, 1))
assert(not placed:adjust(1, 1))
assert(not placed:place(2, 1))
assert(placed:place(1, 2))
assert(placed:undo() and placed:view().placements[1] == 1)
assert(placed:undo() and placed:view().placements[1] == 0)
assert(placed:undo())
assert(placed:view().dice[1] == 2 and placed:view().adjustments == 2)
assert(not placed:undo())
print("session placement and Adjustment undo passed")
local scoring_game = Session.new("thrifty", 1)
assert(not scoring_game:confirm())
assert(scoring_game:begin_placement())
for i = 1, 5 do assert(scoring_game:place(i, i)) end
local preview = scoring_game:preview()
assert(#preview.lines == 1 and preview.lines[1].id == "row1")
assert(preview.lines[1].category == "chance" and preview.lines[1].base_score == 18)
assert(preview.turn_bonus == 10 and preview.total == 28)
assert(scoring_game:view().score == 0)
local events = assert(scoring_game:confirm())
assert(#events == 2 and events[1].points == 18 and events[2].points == 10)
assert(scoring_game:view().phase == "resolving" and scoring_game:view().score == 28)
assert(not scoring_game:confirm() and not scoring_game:undo() and not scoring_game:place(1, 6))
local saved = scoring_game:snapshot()
assert(saved.turn == 2 and saved.phase == "rolling" and saved.score == 28)
assert(saved.board[1] == 2 and saved.scored_lines.row1)
assert(scoring_game:finish_scoring())
assert(table.concat(scoring_game:view().dice) == table.concat(saved.dice))
assert(not scoring_game:finish_scoring())
print("session atomic scoring and next boundary passed")
-- Midturn actions are discarded; repeating the same holds/rolls reproduces outcomes.
local resumed = Session.new("pair_pay", 1)
local original = resumed:snapshot()
assert(resumed:toggle_hold(2) and resumed:roll())
local rolled = table.concat(resumed:view().dice, ",")
assert(resumed:begin_placement() and resumed:adjust(1, -1) and resumed:place(1, 7))
local restored = Session.resume(resumed:snapshot())
assert(restored:view().phase == "rolling" and restored:view().adjustments == 2)
assert(restored:view().placements[1] == 0)
assert(table.concat(restored:view().dice) == table.concat(original.dice))
assert(restored:toggle_hold(2) and restored:roll())
assert(table.concat(restored:view().dice, ",") == rolled)
local exposed = restored:view()
exposed.board[1] = 6
assert(restored:view().board[1] == 0)
print("session deterministic turn-boundary resume passed")

-- Five filled rows complete every row and column once; old rows never pay again.
local board = Session.new("pair_pay", 1)
local line_count = 0
for turn = 1, 5 do
  assert(board:begin_placement())
  if turn == 1 then assert(board:adjust(1, -1)) end
  for die = 1, 5 do assert(board:place(die, (turn - 1) * 5 + die)) end
  local before = board:preview()
  assert(#before.lines == (turn == 5 and 6 or 1))
  for _, line in ipairs(before.lines) do
    line_count = line_count + 1
    assert(not board:view().scored_lines[line.id])
  end
  assert(board:confirm())
  local reload = Session.resume(board:snapshot())
  assert(reload:view().score == before.total and reload:view().adjustments == 1)
  if turn < 5 then
    assert(reload:view().turn == turn + 1 and reload:view().phase == "rolling")
    assert(not reload:place(1, 1))
    assert(board:finish_scoring())
    assert(table.concat(board:view().dice) == table.concat(reload:view().dice))
  else
    assert(reload:view().phase == "results")
    assert(board:finish_scoring() and board:view().phase == "results")
    assert(not reload:confirm() and not reload:roll() and not reload:begin_placement())
  end
end
assert(line_count == 10)
print("session five-turn results, consumables, and score-once passed")
